import assert from 'node:assert/strict';
import {readFileSync,existsSync,readdirSync,statSync} from 'node:fs';
import {Script} from 'node:vm';
const html=readFileSync('dist/index.html','utf8');
assert.ok(Buffer.byteLength(html)<25*1024*1024,'The largest Pages asset must stay below 25 MiB.');
assert.equal(html,readFileSync('index.html','utf8'),'Source ZIP root and Pages HTML must match.');
const scripts=[...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)];
assert.equal(scripts.length,1,'A single inline runtime is required.');
assert.ok(!/\bsrc\s*=|\btype\s*=\s*["']module/i.test(scripts[0][1]),'Direct-open HTML must not request JavaScript modules.');
new Script(scripts[0][2]);
assert.ok(html.includes('data:image/png;base64,'),'The mascot must be embedded.');
assert.ok(html.includes('data:image/svg+xml;base64,'),'The icon must be embedded.');
assert.ok(!/<link[^>]+rel=["']stylesheet/i.test(html),'Styles must be embedded.');
assert.ok(!/src=["']\/(?:src|assets|brain-buddy)/i.test(html),'Runtime assets cannot depend on site-root paths.');
assert.ok(html.includes('hero-centered')&&html.includes('Start timed challenge'));
assert.ok(html.includes('CC BY-SA 3.0'));
assert.ok(html.includes('Start timed cases')&&html.includes('THE APPLIED ANATOMY LAB')&&html.includes('ANATOMICAL READING GUIDE'));
assert.ok(existsSync('dist/anatomy/plates/lower-respiratory/bronchial-tree.svg'));
assert.ok(existsSync('dist/body-selector-v3.webp'));
function checkFiles(dir){for(const f of readdirSync(dir)){const p=dir+'/'+f;if(statSync(p).isDirectory())checkFiles(p);else assert.ok(statSync(p).size<25*1024*1024,p+' exceeds Pages per-file limit');}}checkFiles('dist');
console.log('Passed: standalone script syntax, embedded mascot/styles and adjacent source artwork, no module/server paths, matching local/Pages HTML, timed challenge and attribution.');
